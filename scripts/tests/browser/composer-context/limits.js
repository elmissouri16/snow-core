window.testComposerLimits = async assert => {
  "use strict";
  const {$, tick, wait, posts, latest, draft, chips, clear, upload, textFile, png, reading, send} = contextTest;
  await clear();
  const canvas = document.createElement("canvas"); canvas.width = canvas.height = 1;
  canvas.getContext("2d").fillRect(0, 0, 1, 1);
  const encoded = type => canvas.toDataURL(type).split(",")[1];
  const make = (name, mime, encoded) => new File([Uint8Array.from(atob(encoded), value => value.charCodeAt(0))], name, {type: mime});
  const jpeg = encoded("image/jpeg"), webp = encoded("image/webp");
  upload([make("tiny.jpg", "image/jpeg", jpeg), make("tiny.webp", "image/webp", webp), make("tiny.gif", "image/gif", "R0lGODlhAQABAIAAAAAAAP///yH5BAEAAAAALAAAAAABAAEAAAIBRAA7")]);
  await wait(() => chips().length === 3 && !reading());
  assert(!$(".composer-context-chip.is-error") && ["tiny.jpg", "tiny.webp", "tiny.gif"].every(name => $("[data-composer-context-items]").textContent.includes(name)), "JPEG, WebP and GIF are accepted alongside PNG");
  await clear();
  const padded = new Uint8Array(1100 * 1024); padded.set(Uint8Array.from(atob(png), value => value.charCodeAt(0)));
  upload([new File([padded], "first.png", {type: "image/png"})]); await wait(() => chips().length === 1 && !reading());
  assert(!$(".composer-context-chip.is-error"), "single image below 2MiB is admitted");
  upload([new File([padded], "second.png", {type: "image/png"})]); await wait(() => !reading() && !!$(".composer-context-chip.is-error"));
  assert(chips().length === 2 && /2 MiB/.test($(".composer-context-chip.is-error").textContent), "aggregate image byte budget rejects a second individually valid file");
  await clear();
  upload([textFile("first.txt", "x".repeat(40 * 1024))]); await wait(() => chips().length === 1 && !reading());
  upload([textFile("second.txt", "α".repeat(15 * 1024))]); await wait(() => !reading() && !!$(".composer-context-chip.is-error"));
  assert(/64 KiB/.test($(".composer-context-chip.is-error").textContent), "aggregate file text budget counts UTF-8 bytes rather than characters");
  await clear();
  draft("plain clipboard text");
  const clipboard = new DataTransfer(); clipboard.setData("text/plain", "ordinary pasted text");
  const event = new ClipboardEvent("paste", {clipboardData: clipboard, bubbles: true, cancelable: true});
  $("#live-prompt").dispatchEvent(event);
  assert(!event.defaultPrevented && chips().length === 0, "ordinary text paste retains native textarea behavior rather than becoming an attachment");
  await clear();
  const count = posts("prompt-content").length;
  upload([textFile("uncertain.txt")]); await wait(() => chips().length === 1 && !reading()); draft("Do not retry this"); send();
  await wait(() => posts("prompt-content").length === count + 1);
  latest("prompt-content").reject(); await tick(250);
  assert(chips().length === 1 && $("#live-prompt").value === "Do not retry this" && $("#live-send").disabled, "lost admission response retains exact draft and attachments behind uncertainty guard");
  send(); await tick(150);
  assert(posts("prompt-content").length === count + 1, "lost admission response cannot automatically replay through poll or duplicate Send");
};
